// Generates the client's API types from the Python wire models
// (src/toolbelt/ui/api_models.py):
//
//   python -m toolbelt.ui.api_schema schema   ->  src/api/schema.json
//   python -m toolbelt.ui.api_schema catalog  ->  src/api/catalog.json
//   json-schema-to-typescript(schema.json)    ->  src/api/generated.ts
//
// `pnpm gen:types` rewrites the three files; `pnpm check:types` (the same
// with --check) exits non-zero when any is stale, which is what the
// pre-commit hook and the Python test run.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const webDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(webDir, "..");
const apiDir = join(webDir, "src", "api");

function python(kind) {
  return execFileSync("uv", ["run", "python", "-m", "toolbelt.ui.api_schema", kind], {
    cwd: repoRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });
}

const BANNER = `/* eslint-disable */
// GENERATED by web/scripts/gen-types.mjs from src/toolbelt/ui/api_models.py.
// Do not edit: change the Python models and run \`pnpm gen:types\`.
`;

const schemaText = python("schema");
const generated = await compile(JSON.parse(schemaText), "Wire", {
  bannerComment: BANNER,
  additionalProperties: false,
  format: true,
});

const outputs = {
  "schema.json": schemaText,
  "catalog.json": python("catalog"),
  "generated.ts": generated,
};

const check = process.argv.includes("--check");
let stale = false;
for (const [name, text] of Object.entries(outputs)) {
  const path = join(apiDir, name);
  if (check) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== text) {
      console.error(`stale: src/api/${name} (run \`pnpm gen:types\`)`);
      stale = true;
    }
  } else {
    writeFileSync(path, text);
  }
}
process.exit(stale ? 1 : 0);
